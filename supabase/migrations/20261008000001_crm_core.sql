insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('crm-attachments', 'crm-attachments', false, 3000000, array['image/webp', 'image/jpeg', 'image/png'])
on conflict (id) do nothing;

create policy "crm members read attachments" on storage.objects for select to authenticated
  using (bucket_id = 'crm-attachments' and (select public.crm_has('viewer')));
create policy "crm agents upload attachments" on storage.objects for insert to authenticated
  with check (bucket_id = 'crm-attachments' and (select public.crm_has('agent')) and name ~ '^cases/[0-9]+/[A-Za-z0-9._-]+$');
create policy "crm owner or admin delete attachments" on storage.objects for delete to authenticated
  using (bucket_id = 'crm-attachments' and ((select public.crm_has('admin')) or owner_id = (select auth.uid())::text));
