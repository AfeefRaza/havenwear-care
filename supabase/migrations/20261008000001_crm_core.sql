-- Pakistani phone numbers arrive as 0300…, +92300…, 0092300…, 300…, with
-- dashes/spaces. One canonical key (92XXXXXXXXXX) identifies a customer.
create or replace function public.crm_phone_key(p text)
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$
  select case
    when d = '' then null
    when d ~ '^0092' then substr(d, 3)
    when d ~ '^92[0-9]{10}$' then d
    when d ~ '^0[0-9]{10}$' then '92' || substr(d, 2)
    when d ~ '^3[0-9]{9}$' then '92' || d
    else d
  end
  from (select regexp_replace(coalesce(p, ''), '[^0-9]', '', 'g') as d) x;
$$;

