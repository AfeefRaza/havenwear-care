  id bigint generated always as identity primary key,
  ref text generated always as ('HC-' || lpad(id::text, 5, '0')) stored,
  received_at timestamptz not null default now(),
  channel public.crm_channel not null default 'whatsapp',
  -- Shopify order (Hisab Kitab public.orders.id) + snapshot of who/what
  order_id bigint,
  order_name text check (length(order_name) <= 40),
  customer_name text check (length(customer_name) <= 120),
  phone text check (length(phone) <= 40),
  phone_key text generated always as (public.crm_phone_key(phone)) stored,
  city text check (length(city) <= 80),
  items jsonb not null default '[]' check (jsonb_typeof(items) = 'array' and pg_column_size(items) < 8000),
  courier text check (length(courier) <= 30),
  tracking_number text check (length(tracking_number) <= 40),
  -- Complaint
  type_id smallint references public.crm_complaint_types (id),
  severity public.crm_severity not null,
  status public.crm_status not null default 'open',
  description text not null check (length(description) between 1 and 5000),
  tags text[] not null default '{}',
  -- Workflow
  assignee uuid references public.crm_members (user_id) on delete set null,
  follow_up_at timestamptz,
  due_at timestamptz,
  first_response_at timestamptz,
  resolved_at timestamptz,
  resolution public.crm_resolution,
  resolution_cost numeric(12, 2) not null default 0 check (resolution_cost >= 0),
  resolution_notes text check (length(resolution_notes) <= 5000),
  last_activity_at timestamptz not null default now(),
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
