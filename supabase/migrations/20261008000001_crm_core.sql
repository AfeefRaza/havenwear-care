create or replace function public.crm_guard_member()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.uid()) is null then return coalesce(new, old); end if;
  if tg_op = 'DELETE' then
    if old.user_id = (select auth.uid()) then
      raise exception 'You cannot remove yourself' using errcode = '42501';
    end if;
    return old;
  end if;
  if old.user_id = (select auth.uid()) and (new.role is distinct from old.role or new.active is distinct from old.active) then
    raise exception 'You cannot change your own role or access' using errcode = '42501';
  end if;
  new.user_id := old.user_id;
  return new;
end;
$$;

create trigger crm_members_guard
  before update or delete on public.crm_members
  for each row execute function public.crm_guard_member();

