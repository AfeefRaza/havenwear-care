create or replace function public.crm_norm_order(p text)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  prefix text := coalesce(public.crm_setting('order_prefix') #>> '{}', '#');
  v text := lower(regexp_replace(coalesce(p, ''), '\s+', '', 'g'));
  digits text;
begin
  if v = '' then return null; end if;
  digits := substring(v from '([0-9]{3,})$');
  if digits is null then return v; end if;
  return lower(prefix) || digits;
end;
$$;

-- BEFORE INSERT: fill everything that can be derived so agents type less.
create or replace function public.crm_cases_before_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  t public.crm_complaint_types%rowtype;
  o record;
  s record;
  prior int;
  prof public.crm_customer_profiles%rowtype;
begin
  new.order_name := public.crm_norm_order(new.order_name);

  -- Link the Shopify order and fill customer + shipment details from it
  if new.order_id is null and new.order_name is not null then
    select id into new.order_id from public.orders where lower(name) = new.order_name limit 1;
  end if;
  if new.order_id is not null then
    select name, customer_name, phone, city into o from public.orders where id = new.order_id;
    if found then
      new.order_name := coalesce(new.order_name, lower(o.name));
      new.customer_name := coalesce(nullif(trim(new.customer_name), ''), o.customer_name);
      new.phone := coalesce(nullif(trim(new.phone), ''), o.phone);
      new.city := coalesce(nullif(trim(new.city), ''), o.city);
    end if;
    if new.tracking_number is null then
      select tracking_number, courier into s from public.shipments
       where order_id = new.order_id order by created_at desc limit 1;
      if found then
        new.tracking_number := s.tracking_number;
        new.courier := coalesce(new.courier, s.courier);
      end if;
    end if;
  end if;

  if new.type_id is null then
    select id into new.type_id from public.crm_complaint_types where label = 'Other';
  end if;
  select * into t from public.crm_complaint_types where id = new.type_id;

  new.severity := coalesce(new.severity, t.default_severity, 'non_serious');
  new.due_at := coalesce(new.due_at, new.received_at + make_interval(hours => coalesce(t.sla_hours, 48)));
  if new.status <> 'resolved' then
    new.follow_up_at := coalesce(new.follow_up_at, now() + make_interval(days => coalesce(t.follow_up_days, 2)));
  end if;
  if new.status = 'resolved' and new.resolved_at is null then
    new.resolved_at := now();
  end if;

  -- Customer context tags
  if new.phone is not null then
    select count(*) into prior from public.crm_cases
     where phone_key = public.crm_phone_key(new.phone) and received_at > new.received_at - interval '90 days';
    if prior >= 1 and not 'repeat' = any (new.tags) then
      new.tags := array_append(new.tags, 'repeat');
    end if;
    select * into prof from public.crm_customer_profiles where phone_key = public.crm_phone_key(new.phone);
    if found and prof.flag = 'vip' and not 'vip' = any (new.tags) then
      new.tags := array_append(new.tags, 'vip');
      -- VIPs get a tighter SLA (half)
      new.due_at := new.received_at + make_interval(hours => greatest(1, coalesce(t.sla_hours, 48) / 2));
    end if;
  end if;

  -- Auto-assign to the least-loaded active agent
  if new.assignee is null and new.status <> 'resolved' and coalesce((public.crm_setting('auto_assign'))::boolean, true) then
    select m.user_id into new.assignee
      from public.crm_members m
      left join public.crm_cases c on c.assignee = m.user_id and c.status <> 'resolved'
     where m.active and m.auto_assign and m.role >= 'agent'
     group by m.user_id
     order by count(c.id), random()
     limit 1;
  end if;

  new.last_activity_at := now();
  return new;
end;
$$;

create trigger crm_cases_before_insert
  before insert on public.crm_cases
  for each row execute function public.crm_cases_before_insert();

create or replace function public.crm_cases_before_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  t public.crm_complaint_types%rowtype;
begin
  new.updated_at := now();
  -- Identity columns are immutable
  new.created_by := old.created_by;
  new.created_at := old.created_at;

  if new.order_name is distinct from old.order_name then
    new.order_name := public.crm_norm_order(new.order_name);
  end if;

  if new.status = 'resolved' and old.status <> 'resolved' then
    new.resolved_at := coalesce(new.resolved_at, now());
    new.follow_up_at := null;
  elsif new.status <> 'resolved' and old.status = 'resolved' then
    new.resolved_at := null;
    new.resolution := null;
    select * into t from public.crm_complaint_types where id = new.type_id;
    new.follow_up_at := coalesce(new.follow_up_at, now() + make_interval(days => coalesce(t.follow_up_days, 1)));
    new.due_at := now() + make_interval(hours => coalesce(t.sla_hours, 24));
  elsif new.status <> 'resolved' then
    new.resolved_at := null;
  end if;

  if new.type_id is distinct from old.type_id and new.due_at is not distinct from old.due_at then
    select * into t from public.crm_complaint_types where id = new.type_id;
    new.due_at := new.received_at + make_interval(hours => coalesce(t.sla_hours, 48));
  end if;
  return new;
end;
$$;

create trigger crm_cases_before_update
  before update on public.crm_cases
  for each row execute function public.crm_cases_before_update();

-- AFTER triggers write the timeline, so the client never double-writes history.
create or replace function public.crm_cases_after_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
begin
  if tg_op = 'INSERT' then
    insert into public.crm_case_events (case_id, kind, body, meta, actor)
    values (new.id, 'created', null, jsonb_build_object('channel', new.channel, 'assignee', new.assignee), actor);
    return new;
  end if;

  if new.status is distinct from old.status then
    if new.status = 'resolved' then
      insert into public.crm_case_events (case_id, kind, body, meta, actor)
      values (new.id, 'resolved', new.resolution_notes,
              jsonb_build_object('from', old.status, 'resolution', new.resolution, 'cost', new.resolution_cost), actor);
    elsif old.status = 'resolved' then
      insert into public.crm_case_events (case_id, kind, meta, actor)
      values (new.id, 'reopened', jsonb_build_object('to', new.status), actor);
    else
      insert into public.crm_case_events (case_id, kind, meta, actor)
      values (new.id, 'status', jsonb_build_object('from', old.status, 'to', new.status), actor);
    end if;
  end if;
  if new.assignee is distinct from old.assignee then
    insert into public.crm_case_events (case_id, kind, meta, actor)
    values (new.id, 'assigned', jsonb_build_object('from', old.assignee, 'to', new.assignee), actor);
  end if;
  if new.follow_up_at is distinct from old.follow_up_at and new.follow_up_at is not null and new.status <> 'resolved' then
    insert into public.crm_case_events (case_id, kind, meta, actor)
    values (new.id, 'follow_up', jsonb_build_object('at', new.follow_up_at), actor);
  end if;
  if new.type_id is distinct from old.type_id or new.severity is distinct from old.severity then
    insert into public.crm_case_events (case_id, kind, meta, actor)
    values (new.id, 'edit', jsonb_build_object(
      'type_from', old.type_id, 'type_to', new.type_id, 'severity_from', old.severity, 'severity_to', new.severity), actor);
  end if;
  return new;
end;
$$;

create trigger crm_cases_after_insert
  after insert on public.crm_cases
  for each row execute function public.crm_cases_after_change();

create trigger crm_cases_after_update
  after update of status, assignee, follow_up_at, type_id, severity on public.crm_cases
  for each row execute function public.crm_cases_after_change();

-- Events keep the case fresh: activity time, first response, and a customer
-- reply automatically moves an "awaiting customer" case back into progress.
create or replace function public.crm_events_after_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.kind in ('note', 'contact', 'attachment') then
    update public.crm_cases c set
      last_activity_at = now(),
      first_response_at = case
        when c.first_response_at is null and new.kind = 'contact' and coalesce(new.meta ->> 'direction', 'out') = 'out'
        then new.created_at else c.first_response_at end,
      status = case
        when new.kind = 'contact' and new.meta ->> 'direction' = 'in' and c.status = 'awaiting_customer' then 'in_progress'::public.crm_status
        when new.kind = 'contact' and coalesce(new.meta ->> 'direction', 'out') = 'out' and c.status = 'open' then 'in_progress'::public.crm_status
        else c.status end
    where c.id = new.case_id;
  end if;
  return new;
end;
$$;

create trigger crm_events_after_insert
  after insert on public.crm_case_events
  for each row execute function public.crm_events_after_insert();

