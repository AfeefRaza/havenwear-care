-- =====================================================================
-- Havenwear Care — core schema
--
-- Lives inside the Hisab Kitab Supabase project so that the Shopify orders,
-- customers and courier tracking it already syncs are reused, never copied.
-- Everything here is additive and prefixed `crm_`; Hisab Kitab tables are
-- only READ (through security-definer functions that expose support-relevant
-- columns — never costs, settlements or other finance data).
--
-- Access model: a signed-in user has CRM access only when they have an
-- active row in crm_members (viewer < agent < admin). Hisab Kitab roles are
-- unrelated, so CRM users get no finance access and vice versa.
-- =====================================================================

